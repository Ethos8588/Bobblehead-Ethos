/**
 * OPTIONAL. You can ignore this file entirely and the site still works.
 *
 * What it does: makes one Voyage AI call for all your trigger phrases and
 * saves the result to data/embeddings.json. The live site then uses that file
 * instead of computing them itself, which makes the first message after a
 * quiet period a bit faster and saves a handful of tokens.
 *
 * To run it (on your own computer, with Node 20+ installed):
 *
 *     VOYAGE_API_KEY=your-key-here npm run precompute-embeddings
 *
 * On Windows PowerShell:
 *
 *     $env:VOYAGE_API_KEY="your-key-here"; npm run precompute-embeddings
 *
 * Then commit the new data/embeddings.json and push. Re-run it whenever you
 * change the trigger phrases in data/responses.json.
 */

import { writeFileSync } from 'node:fs';
import { buildReferenceTexts, voyageEmbed, MATCHING } from '../lib/classifier.js';

const apiKey = process.env.VOYAGE_API_KEY;
if (!apiKey) {
  console.error('\nNo VOYAGE_API_KEY found in your environment.');
  console.error('Set it first, then run this again. See the comment at the top of this file.\n');
  process.exit(1);
}

const model = MATCHING.embeddingModel || 'voyage-4-lite';
const items = buildReferenceTexts();

console.log(`Embedding ${items.length} reference phrases with ${model}...`);

const vectors = await voyageEmbed(items.map((i) => i.text), 'document', apiKey);

const out = {
  _readme: 'Generated by scripts/precompute-embeddings.mjs. Safe to delete; it will be rebuilt automatically at runtime.',
  model,
  generatedAt: new Date().toISOString(),
  items: items.map((item, i) => ({ ...item, vector: vectors[i] })),
};

const target = new URL('../data/embeddings.json', import.meta.url);
writeFileSync(target, JSON.stringify(out));

console.log(`Done. Wrote data/embeddings.json (${items.length} vectors, ${vectors[0].length} dimensions).`);
console.log('Commit that file and push to redeploy.\n');
